// Real application scripts, isolated transport. No live Supabase writes.
const assert = require("node:assert/strict");
const { start } = require("./support/loading-harness.cjs");
(async () => {
  const h = await start();
  const run = source => h.evaluate(`(async()=>{${source}})()`);
  const ready = () => h.waitFor('!document.body.classList.contains("app-auth-pending")');
  try {
    for (const width of [320, 375, 768, 1280, 1920]) {
      await h.viewport(width);
      await h.open("index.html#bookings"); await ready();
      assert.ok(await h.evaluate('document.querySelector(".booking-next-action").textContent.includes("Provider")'));
      await run('document.querySelector(".booking-contract").open=true');
      assert.ok(await h.evaluate('document.querySelector(".booking-contract").textContent.includes("Appointment")'));
      await run('await openProviderProfile("p1","s1")');
      assert.ok(await h.evaluate('document.querySelector(".provider-evidence").textContent.includes("does not guarantee service quality")'));
      await run('document.querySelector("[data-showcase-jump=reviews]").click()');
      assert.equal(await h.evaluate('document.activeElement.textContent'), "Student reviews");
      assert.ok(await h.evaluate('document.documentElement.scrollWidth<=innerWidth+1'));
      await run('document.querySelector("#provider-detail-modal").close()');
    }
    console.log("PASS booking summaries and provider evidence at five viewport widths");
    await h.viewport(375);
    await h.open("index.html#home"); await ready();
    await run('globalSearch.value="tutoring";globalSearch.dispatchEvent(new Event("input",{bubbles:true}));document.querySelector("#marketplace-filters [name=max]").value="80";document.querySelector("#marketplace-filters").dispatchEvent(new Event("input",{bubbles:true}))');
    await h.open("index.html#home"); await ready();
    assert.equal(await h.evaluate('globalSearch.value'), "tutoring");
    assert.equal(await h.evaluate('document.querySelector("#marketplace-filters [name=max]").value'), "80");
    await run('document.querySelector("[data-discovery-focus=filters]").click()');
    assert.equal(await h.evaluate('document.activeElement.name'), "min");
    await run('document.querySelector("[data-discovery-focus=search]").click()');
    assert.equal(await h.evaluate('document.activeElement.id'), "global-search");
    console.log("PASS search restoration and mobile keyboard access to filters");
    await run('openBooking("p1","s1");document.querySelector("#booking-note").value="Bring practice problems";document.querySelector("#booking-note").dispatchEvent(new Event("input",{bubbles:true}));document.querySelector("#booking-modal").close()');
    await h.open("index.html#home"); await ready();
    await run('openBooking("p1","s1")');
    assert.equal(await h.evaluate('document.querySelector("#booking-note").value'), "Bring practice problems");
    assert.ok(await h.evaluate('document.querySelector("#booking-save-status").textContent.includes("Restored")'));
    await run('window.__attempt=skillmateJourney.requestId("same-attempt")');
    const beforeReload = await h.evaluate('window.__attempt');
    await h.open("index.html#home"); await ready();
    const first = await h.evaluate('skillmateJourney.requestId("same-attempt")');
    assert.equal(first, beforeReload);
    const second = await h.evaluate('skillmateJourney.requestId("same-attempt")');
    assert.equal(first, second);
    assert.notEqual(await h.evaluate('skillmateJourney.requestId("different-attempt")'), first);
    await run('openBooking("p1","s1");window.dispatchEvent(new Event("offline"))');
    assert.ok(await h.evaluate('document.querySelector("#booking-save-status").textContent.includes("offline")'));
    await run('document.dispatchEvent(new CustomEvent("skillmate:booking-save",{detail:{state:"failed"}}))');
    assert.ok(await h.evaluate('Boolean(document.querySelector("#booking-save-status button"))'));
    await run('document.dispatchEvent(new CustomEvent("skillmate:booking-save",{detail:{state:"saved",providerId:"p1",serviceId:"s1",agreementId:""}}));document.querySelector("#booking-modal").close()');
    await h.open("index.html#home"); await ready();
    assert.equal(await h.evaluate('skillmateJourney.bookingDraft("p1","s1")'), null);
    await run(`window.__inserts=[];window.__from=appSupabase.from;
      appSupabase.from=table=>{
        if(table!=="bookings")return window.__from(table);
        const builder={select(){return this},eq(){return this},async maybeSingle(){return {data:{id:window.__inserts[0].id},error:null}},
          async insert(payload){window.__inserts.push(payload);return {error:window.__inserts.length===1?{message:"Connection interrupted"}:{code:"23505"}}}};
        return builder;
      };
      openBooking("p1","s1");document.querySelector("#booking-location-type").value="campus";
      document.querySelector("#booking-form").requestSubmit();`);
    await h.waitFor('!bookingSubmissionPending && document.querySelector("#booking-modal").open');
    assert.equal(await h.evaluate('window.__inserts.length'), 1);
    await run('document.querySelector("#booking-save-status button").click()');
    await h.waitFor('!bookingSubmissionPending && window.__inserts.length===2');
    assert.equal(await h.evaluate('window.__inserts[0].id'), await h.evaluate('window.__inserts[1].id'));
    assert.equal(await h.evaluate('document.querySelector("#booking-modal").open'), false);
    await run('appSupabase.from=window.__from');
    await run(`connectedServices.push({...connectedServices.find(service=>service.id==='s1'),id:'s-extra',title:'Another service'});
      openBooking('p1','s1');document.querySelector('#booking-note').value='First service instructions';
      document.querySelector('#booking-note').dispatchEvent(new Event('input',{bubbles:true}));
      document.querySelector('#booking-service').value='s-extra';document.querySelector('#booking-service').dispatchEvent(new Event('change',{bubbles:true}));`);
    assert.equal(await h.evaluate('document.querySelector("#booking-note").value'), "");
    await run(`document.querySelector('#booking-note').value='Second service instructions';document.querySelector('#booking-note').dispatchEvent(new Event('input',{bubbles:true}));
      document.querySelector('#booking-service').value='s1';document.querySelector('#booking-service').dispatchEvent(new Event('change',{bubbles:true}));`);
    assert.equal(await h.evaluate('document.querySelector("#booking-note").value'), "First service instructions");
    await run(`window.__setItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new Error('Storage quota exceeded')};
      document.querySelector('#booking-note').value='Latest edit while storage is full';document.querySelector('#booking-note').dispatchEvent(new Event('input',{bubbles:true}));
      document.querySelector('#booking-modal').close();openBooking('p1','s1');Storage.prototype.setItem=window.__setItem;`);
    assert.equal(await h.evaluate('document.querySelector("#booking-note").value'), "Latest edit while storage is full");
    await run(`window.__removeItem=Storage.prototype.removeItem;Storage.prototype.removeItem=function(){throw new Error('Storage denied')};
      document.dispatchEvent(new CustomEvent('skillmate:booking-save',{detail:{state:'saved',providerId:'p1',serviceId:'s1',agreementId:''}}));
      document.querySelector('#booking-modal').close();openBooking('p1','s1');Storage.prototype.removeItem=window.__removeItem;`);
    assert.equal(await h.evaluate('document.querySelector("#booking-note").value'), "");
    await run(`document.querySelector('#booking-modal').close();document.querySelector('#booking-service').value='s-extra';document.querySelector('#booking-service').dispatchEvent(new Event('change',{bubbles:true}));`);
    assert.equal(await h.evaluate('document.querySelector("#booking-modal").open'), false);
    console.log("PASS service drafts stay separate and storage failure cannot restore stale or cleared edits");
    await run(`document.querySelector('#booking-modal').close();window.__slots=skillmateGrowth.refreshSlots;
      skillmateGrowth.refreshSlots=async()=>{const select=document.querySelector('#booking-slot');select.replaceChildren(new Option('Choose a time',''));
        await new Promise(resolve=>setTimeout(resolve,30));select.add(new Option('10 AM','2030-01-01T10:00:00Z'));};openBooking('p1','s1');`);
    await h.waitFor('document.querySelector("#booking-slot").options.length===2');
    await run(`document.querySelector('#booking-slot').value='2030-01-01T10:00:00Z';document.querySelector('#booking-slot').dispatchEvent(new Event('change',{bubbles:true}));document.querySelector('#booking-modal').close();`);
    await h.open("index.html#home"); await ready();
    await run(`window.__slots=skillmateGrowth.refreshSlots;skillmateGrowth.refreshSlots=async()=>{const select=document.querySelector('#booking-slot');select.replaceChildren(new Option('Choose a time',''));await new Promise(resolve=>setTimeout(resolve,30));select.add(new Option('10 AM','2030-01-01T10:00:00Z'));};openBooking('p1','s1');`);
    await h.waitFor('document.querySelector("#booking-slot").value==="2030-01-01T10:00:00Z"');
    await run(`connectedServices.push({...connectedServices.find(service=>service.id==='s1'),id:'s-other',title:'Other service'});
      window.__slotCalls=0;const refresh=skillmateGrowth.refreshSlots;skillmateGrowth.refreshSlots=()=>{window.__slotCalls++;return refresh()};
      document.querySelector('#booking-service').value='s-other';document.querySelector('#booking-service').dispatchEvent(new Event('change',{bubbles:true}));`);
    assert.equal(await h.evaluate('window.__slotCalls'), 1);
    await h.wait(50);
    await run(`document.querySelector('#booking-service').value='s1';document.querySelector('#booking-service').dispatchEvent(new Event('change',{bubbles:true}));`);
    await h.waitFor('document.querySelector("#booking-slot").value==="2030-01-01T10:00:00Z"');
    assert.equal(await h.evaluate('skillmateJourney.bookingDraft("p1","s1").slot'), "2030-01-01T10:00:00Z");
    await run(`document.querySelector('#booking-modal').close();openBooking('p1','s1');openBooking('p2','s2');`);
    await h.wait(80);
    assert.equal(await h.evaluate('document.querySelector("#booking-slot").value'), "");
    await run('skillmateGrowth.refreshSlots=window.__slots');
    assert.deepEqual(h.pageErrors, []);
    console.log("PASS interrupted drafts restore, saved drafts clear, offline feedback and stable retry IDs");
    console.log("PASS interrupted booking retries reuse the same ID and reconcile an existing saved request");
    console.log("PASS valid appointment slots restore after reload and obsolete restores cannot change another booking");
  } finally { await h.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
